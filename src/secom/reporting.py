"""Write experiment tables to reports/ so that no result is ever typed by hand."""

import json
from pathlib import Path
from typing import Any

import pandas as pd

from secom.config import REPORTS_DIR

RESULTS_MARKDOWN = "results.md"
RESULTS_JSON = "results.json"
METRIC_DECIMALS = 3


def _format_cell(value: object) -> str:
    if isinstance(value, float):
        return "n/a" if pd.isna(value) else f"{value:.{METRIC_DECIMALS}f}"
    return str(value)


def markdown_table(frame: pd.DataFrame) -> str:
    """Render a DataFrame as a GitHub-flavoured Markdown table."""
    header = "| " + " | ".join(str(column) for column in frame.columns) + " |"
    separator = "|" + "---|" * len(frame.columns)
    rows = [
        "| " + " | ".join(_format_cell(value) for value in row) + " |"
        for row in frame.itertuples(index=False, name=None)
    ]
    return "\n".join([header, separator, *rows])


def write_results(
    sections: dict[str, str], data: dict[str, Any], directory: Path = REPORTS_DIR
) -> None:
    """Write titled Markdown sections and the machine-readable results next to each other."""
    directory.mkdir(parents=True, exist_ok=True)
    body = ["# Experiment results", "", "Generated by `run_experiments.py`. Do not edit by hand."]
    for title, content in sections.items():
        body += ["", f"## {title}", "", content]
    (directory / RESULTS_MARKDOWN).write_text("\n".join(body) + "\n", encoding="utf-8")
    (directory / RESULTS_JSON).write_text(
        json.dumps(data, indent=2, default=str) + "\n", encoding="utf-8"
    )
